# Experiment 12: RAG Data Indexing and Retrieval Using FAISS + Gemini

# %pip install -q -U langchain-community langchain-text-splitters langchain-google-genai faiss-cpu

import os
from getpass import getpass

from langchain_core.documents import Document
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_google_genai import GoogleGenerativeAIEmbeddings
from langchain_community.vectorstores import FAISS

# --------------------------------------------------
# STEP 1: Configure Gemini API key
# --------------------------------------------------

os.environ.pop("GOOGLE_API_KEY", None)
os.environ["GOOGLE_API_KEY"] = getpass(
    "Enter your Gemini API key: "
)

# --------------------------------------------------
# STEP 2: Define sample text
# --------------------------------------------------

sample_text = """
Climate change refers to long-term changes in temperatures
and weather patterns. Human activities, especially burning
fossil fuels such as coal, oil, and gas, are the main drivers
of recent global warming.

One major effect of climate change is rising global temperature.
Heat waves are becoming more frequent and intense in many regions.
Higher temperatures can affect human health, agriculture,
water supplies, and natural ecosystems.

Climate change also contributes to melting glaciers and polar ice.
As land ice melts and ocean water expands when heated,
sea levels rise. Coastal communities may experience more flooding,
erosion, and damage to buildings and infrastructure.

Extreme weather events such as heavy rainfall, droughts, and
some severe storms can create serious challenges. These events
may damage crops, disrupt transportation, and threaten wildlife.
The exact effects vary by location and depend on local conditions.

Reducing greenhouse gas emissions can help limit future warming.
Renewable energy sources such as solar and wind power can reduce
dependence on fossil fuels. Energy efficiency, forest protection,
and sustainable transportation can also help address climate change.
"""

documents = [Document(page_content=sample_text)]

# --------------------------------------------------
# STEP 3: Split text into chunks
# --------------------------------------------------

splitter = RecursiveCharacterTextSplitter(
    chunk_size=300,
    chunk_overlap=30
)

chunks = splitter.split_documents(documents)

print("Number of chunks:", len(chunks))

# --------------------------------------------------
# STEP 4: Create Gemini embeddings
# --------------------------------------------------

embeddings = GoogleGenerativeAIEmbeddings(
    model="models/gemini-embedding-001"
)

# --------------------------------------------------
# STEP 5: Create FAISS vector store
# --------------------------------------------------

vectorstore = FAISS.from_documents(
    documents=chunks,
    embedding=embeddings
)

print("FAISS vector store created successfully.")

# --------------------------------------------------
# STEP 6: Define retrieval query
# --------------------------------------------------

query = "What are the effects of climate change?"

print("\nQuery:", query)

# --------------------------------------------------
# STEP 7: Retrieve the top 2 relevant chunks
# --------------------------------------------------

results = vectorstore.similarity_search_with_relevance_scores(
    query,
    k=2
)

print("\nTop 2 chunks:\n")

output_lines = [
    f"Number of chunks: {len(chunks)}",
    f"Query: {query}",
    "",
    "Top 2 chunks:"
]

for rank, (document, score) in enumerate(results, start=1):
    print(f"Result {rank}")
    print(f"Relevance score: {score:.4f}")
    print("Chunk:", document.page_content)
    print("-" * 60)

    output_lines.extend([
        f"Result {rank}",
        f"Relevance score: {score:.4f}",
        f"Chunk: {document.page_content}",
        "-" * 60
    ])

# --------------------------------------------------
# STEP 8: Save output for GitHub submission
# --------------------------------------------------

with open("output.txt", "w", encoding="utf-8") as file:
    file.write("\n".join(output_lines))

print("\nResults saved to output.txt")

